import AppKit
import CryptoKit

/// 一次「复制」被识别出来的结果。
/// - image: 已经是可以直接落盘的 PNG 数据
/// - text:  纯文本（富文本降级而来，只留文字，不留格式）
/// - link:  整段内容就是一个网页地址
enum Copied {
    case image(Data)
    case text(String)
    case link(URL)
}

/// 盯住剪贴板，把每次复制都挂上绳。
///
/// 本文件原来是 Tendedero 自带的「只挂复制的图片」监听器，本地改版把它扩成三种都能挂：
/// 图片照旧原样落盘，文字和链接画成一张卡片再落盘——因为线上的一条就是一个图片文件，
/// 画成图片才能直接复用拖拽、复制、QuickLook、Markup 全部能力。
///
/// 默认关闭，从菜单栏打开。剪贴板没有变更通知，只能轮询 changeCount。
///
/// 合并说明：原先这部分能力由外部程序「万能挂载」承担——它往截图文件夹里写文件，
/// 晾衣架再当新截图捡起来。两个进程靠文件夹交接，用起来必须同时开着。
/// 现在直接长在进程内，只装一个 App 就够，也不再需要「万能挂载」。
@MainActor
final class ClipboardWatcher {

    /// 挂上去之后回调。参数是最终落盘的文件 URL。
    /// 调用时机：图片 / 文字卡 / 链接卡写进文件夹之后。
    private let onNew: (URL) -> Void

    private var timer: Timer?

    /// 上一次看到的剪贴板变化计数
    private var lastCount = NSPasteboard.general.changeCount

    /// 上一条挂上去的内容指纹。很多 App 会把同一条内容重复写进剪贴板，
    /// 只挂一次；被取下之后再复制同一个内容，算新的一次，会重新挂。
    private var last: (digest: String, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    /// 菜单栏开关，记住用户的选择。
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    // MARK: - 文件名前缀

    /// 三种卡片的文件名前缀。
    /// 点击卡片时靠它区分「这是文字卡（要还原成原文）还是真图片（照旧复制图片）」。
    /// 常量字符串，后台队列也要读，所以标 nonisolated
    nonisolated static let textPrefix = "文字"
    nonisolated static let linkPrefix = "链接"
    nonisolated static let imagePrefix = "图片"

    // MARK: - 过滤规则

    /// 密码管理器、浏览器隐私复制会打上这些标记（nspasteboard.org 事实标准）。
    /// 命中任意一条就整条丢弃——宁可不挂，也不要把密码挂到屏幕上。
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// 超过这个体积就不是截图了，别把几十兆的原图搬进文件夹。
    private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000

    // MARK: - 生命周期

    init(onNew: @escaping (URL) -> Void) {
        self.onNew = onNew
    }

    /// 开始轮询。
    /// 调用时机：App 启动时（总是调，因为「点卡片还原文字」不受开关影响），
    /// 以及菜单里打开这个开关时。
    func start() {
        guard timer == nil else { return }
        // 启动前剪贴板里残留的旧内容不该被挂上去，先把计数当基线
        lastCount = NSPasteboard.general.changeCount
        // 0.15 秒一次：用户点完卡片到按 ⌘V 可能只有零点几秒，
        // 我们得赶在他粘贴之前把剪贴板换回原文
        let timer = Timer(timeInterval: 0.15, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 轮询一次。
    /// 调用时机：定时器每 0.15 秒一次。
    /// 只读 changeCount，没有变化就立刻返回，开销可以忽略。
    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count

        // ① 先看这次变化是不是「用户点了我们自己做的文字卡 / 链接卡」。
        //    是的话把剪贴板换回原文，然后就此打住，不再挂一张新卡。
        //    这一步不看开关：卡片已经挂在线上，关掉监听也该能点出文字来。
        if restoreTextIfCardWasCopied(pb) {
            // 换内容后 changeCount 又变了，同步掉，否则下一轮会被当成新复制
            lastCount = pb.changeCount
            return
        }

        // ② 开关关着就不挂新东西
        guard Self.isEnabled else { return }

        guard let copied = Self.read(pb) else { return }

        // 去重：同一条内容连续复制多次只挂一次
        let digest = Self.digest(of: copied)
        guard digest != last?.digest else { return }

        // 这一瞬间的前台 App 基本就是复制来源
        let source = NSWorkspace.shared.frontmostApplication?.localizedName ?? "剪贴板"
        // 外观必须在主线程取好再传进后台，AppKit 对象不能跨线程用
        let isDark = NSApp.effectiveAppearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua
        let now = Date()

        // 画卡、抓标题都要几十毫秒到几秒，放后台做，绝不卡住菜单栏和绳子
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let png: Data?
            let kind: String
            /// 原文。文字卡和链接卡要存下来，用户点卡片时靠它还原成文字。
            /// 图片卡存 nil——点一下照旧复制图片，保持原版行为。
            let original: String?

            switch copied {
            case .image(let data):
                // 图片原样保存，不重绘，保证和截图一模一样
                png = data
                kind = ClipboardWatcher.imagePrefix
                original = nil
            case .text(let text):
                png = CardRenderer.textCard(text: text, source: source, date: now, isDark: isDark)
                kind = ClipboardWatcher.textPrefix
                original = text
            case .link(let url):
                // 抓标题走网络，所以这里已经在后台队列了
                let title = WebTitle.fetch(url)
                png = CardRenderer.linkCard(url: url, title: title, source: source,
                                            date: now, isDark: isDark)
                kind = ClipboardWatcher.linkPrefix
                original = url.absoluteString
            }

            DispatchQueue.main.async {
                // 这期间用户又复制了别的东西：那次才算数，这条丢掉。
                // 开关被关掉、或者已经停止监听：也不挂。
                guard let png, NSPasteboard.general.changeCount == count,
                      let self, self.timer != nil else { return }
                self.save(png, kind: kind, text: original, digest: digest)
            }
        }
    }

    // MARK: - 识别这一次复制是什么

    /// 读懂剪贴板里这一次复制的内容。
    /// 调用时机：check 确认 changeCount 变了、且开关是开的之后。
    /// - Returns: nil 表示这一次不该挂（文件、隐私内容、空内容）
    ///
    /// 判断顺序是有讲究的：
    /// 1. 隐私标记最优先，命中就整条丢弃；
    /// 2. 复制的是文件或文件夹——需求里明确不要，而且复制文件时剪贴板里同时有文件名文本，
    ///    所以必须在文本判断之前拦掉；
    /// 3. 有文字就当文字处理。Excel、Numbers、网页复制富文本时往往同时捎带一张
    ///    渲染好的图片，用户的意图是文字，所以文字优先；
    /// 4. 都没有才是图片。
    private static func read(_ pb: NSPasteboard) -> Copied? {
        let types = pb.types ?? []

        if types.contains(where: { privateTypes.contains($0) }) { return nil }
        if types.contains(.fileURL) { return nil }

        if let raw = pb.string(forType: .string) {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                // 整段就是一个网址 → 走链接卡，比一堆裸链接好看
                if let url = singleURL(in: trimmed) { return .link(url) }
                return .text(raw)
            }
        }

        // 直接拿 PNG 原始字节，避免二次编码导致颜色 / 透明度变化
        if let png = pb.data(forType: .png), png.count <= maxBytes {
            return .image(png)
        }
        // 微信、QQ 截图、Preview 等常常只给 TIFF，这里转一次
        if let tiff = pb.data(forType: .tiff), let png = png(from: tiff) {
            return .image(png)
        }

        return nil
    }

    /// 把整段文本判断成单个网页地址。
    /// 只有「不含空格换行、能解析出 http/https、主机名带点」才认，避免把普通句子误判成链接。
    /// 调用时机：read 的文本分支末尾。
    private static func singleURL(in text: String) -> URL? {
        // 网址不会带空白字符；带空白说明是句子
        if text.contains(where: { $0.isWhitespace }) { return nil }
        guard text.count >= 8, text.count <= 2048 else { return nil }
        guard let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return nil }
        guard scheme == "http" || scheme == "https" else { return nil }
        guard let host = url.host, host.contains(".") else { return nil }
        return url
    }

    /// TIFF → PNG。剪贴板里的 TIFF 往往是未压缩的大块，转成 PNG 体积小很多。
    /// 同时校验尺寸，挡住「解码出来是个巨型位图」的病态输入。
    /// 调用时机：read 只拿到 TIFF 时。
    nonisolated private static func png(from tiff: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: tiff),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    /// 给内容算指纹，用于去重。
    /// 调用时机：check 判断「这条是不是刚挂过」。
    private static func digest(of copied: Copied) -> String {
        let data: Data
        switch copied {
        case .image(let png): data = png
        case .text(let text): data = Data(text.utf8)
        case .link(let url): data = Data(url.absoluteString.utf8)
        }
        return SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - 落盘

    /// 把卡片写进截图文件夹，写完通知外面挂上线。
    /// 调用时机：check 的后台任务算好 PNG、回到主线程之后。
    /// - Parameters:
    ///   - png: 卡片图片数据
    ///   - kind: 文件名前缀（文字 / 链接 / 图片）
    ///   - text: 原文；非空时在旁边存一个同名 .txt，点卡片时靠它还原文
    ///   - digest: 内容指纹，记下来给下一次去重用
    private func save(_ png: Data, kind: String, text: String?, digest: String) {
        // 上一条还挂在网上，同一条内容再复制一次就不重复挂了
        if let last, last.digest == digest,
           FileManager.default.fileExists(atPath: last.url.path) { return }

        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("\(kind)_\(Self.stamp()).png")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("\(kind)_\(Self.stamp()) \(n).png")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            // .atomic 会先写临时文件再一次性改名，
            // 文件监听只会看到「完整出现的图片」，不会读到半截
            try png.write(to: url, options: .atomic)
            // 复制来的东西可能是私密的：只有本用户能读
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            // 原文写进图片自己的扩展属性，删图片时跟着一起走。
            // 写失败不影响挂载，所以不看返回值。
            if let text, !text.isEmpty {
                Self.setOriginalText(text, for: url)
            }
            last = (digest, url)
            onNew(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copied item: \(error.localizedDescription, privacy: .public)")
        }
    }

    // MARK: - 点卡片还原原文

    /// 原文存在 PNG 自己的扩展属性里，而不是旁边单独一个 .txt。
    /// 调用时机：save 写完 PNG 之后。
    ///
    /// 为什么不用旁车文件：卡片被删掉时，PNG 由 Line 自己 trash 掉（那一份是有权限的），
    /// 但再回头删那个 .txt 会在 TCC 下静默失败，于是文件夹里越积越多没有主人的 txt。
    /// 存成扩展属性就没有这个问题——删图片本身，原文跟着一起没了。
    /// 代价是单个属性有大小上限（约 128KB），所以超长的只留前面一部分。
    private nonisolated static let textAttribute = "com.local.liangyijia.copiedText"
    private nonisolated static let maxAttributeBytes = 100_000

    /// 把原文写进卡片的扩展属性。
    /// 调用时机：save 里 PNG 落盘之后。
    private nonisolated static func setOriginalText(_ text: String, for card: URL) {
        var payload = Data(text.utf8)
        if payload.count > maxAttributeBytes {
            // 太长了放不进属性，只留前面一部分，并明确告诉用户
            let cut = String(text.prefix(maxAttributeBytes / 3)) + "\n…（原文过长，只保留了前一部分）"
            payload = Data(cut.utf8)
        }
        _ = card.withUnsafeFileSystemRepresentation { path -> Int32 in
            guard let path else { return -1 }
            return payload.withUnsafeBytes { buffer in
                setxattr(path, textAttribute, buffer.baseAddress, payload.count, 0, 0)
            }
        }
    }

    /// 读回某张卡片对应的原文：先看扩展属性，再看早期的 .txt 旁车。
    /// 调用时机：用户点文字卡 / 链接卡，以及悬停预览要显示全文时。
    static func originalText(of card: URL) -> String? {
        if let text = attributeText(of: card) {
            return text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : text
        }
        // 兼容早期用旁车文件的卡片
        guard let text = try? String(contentsOf: sidecarURL(for: card), encoding: .utf8) else {
            return nil
        }
        return text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : text
    }

    /// 从扩展属性里读原文；没有这个属性就返回 nil。
    /// 调用时机：originalText 第一步。
    private nonisolated static func attributeText(of card: URL) -> String? {
        let size = card.withUnsafeFileSystemRepresentation { path -> Int in
            guard let path else { return -1 }
            return getxattr(path, textAttribute, nil, 0, 0, 0)
        }
        guard size > 0 else { return nil }

        var buffer = [UInt8](repeating: 0, count: size)
        let read = card.withUnsafeFileSystemRepresentation { path -> Int in
            guard let path else { return -1 }
            return getxattr(path, textAttribute, &buffer, size, 0, 0)
        }
        guard read == size else { return nil }
        return String(bytes: buffer, encoding: .utf8)
    }

    /// 早期版本的原文旁车路径（把 .png 换成 .txt）。只为兼容旧卡片保留读取。
    /// 调用时机：originalText 读扩展属性失败时的兜底。
    static func sidecarURL(for card: URL) -> URL {
        card.deletingPathExtension().appendingPathExtension("txt")
    }

    /// 检查剪贴板是不是「刚点了我们生成的文字卡 / 链接卡」，是就换成原文。
    /// 调用时机：check 发现剪贴板变化后、正常挂载之前。
    ///
    /// 判断依据来自 Line.putOnClipboard：卡片被复制时只写 png + 文件路径，不写纯文本。
    /// 所以「有 fileURL、没有 string」这个组合只会在点卡片时出现，
    /// 用户正常复制文字或图片都不会满足，不会误伤。
    /// - Returns: true 表示已经处理过，调用方应该跳过本次挂载
    private func restoreTextIfCardWasCopied(_ pb: NSPasteboard) -> Bool {
        // 有纯文本说明是用户自己复制的，放行
        guard pb.string(forType: .string) == nil else { return false }
        guard let raw = pb.string(forType: .fileURL),
              let url = URL(string: raw), url.isFileURL else { return false }

        // 必须是截图文件夹里、我们自己做的那种卡片
        guard url.deletingLastPathComponent().standardizedFileURL
            == Inbox.folder.standardizedFileURL else { return false }
        let name = url.deletingPathExtension().lastPathComponent
        guard name.hasPrefix(Self.textPrefix) || name.hasPrefix(Self.linkPrefix) else {
            return false
        }

        guard let text = Self.originalText(of: url) else { return false }

        pb.clearContents()
        pb.setString(text, forType: .string)
        return true
    }

    // MARK: - 工具

    /// 文件名用的时间戳，精确到毫秒，避免同一秒连挂多张时重名。
    private static var stampFormatter: DateFormatter = {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyyMMdd_HHmmss_SSS"
        return f
    }()

    private static func stamp() -> String {
        stampFormatter.string(from: Date())
    }
}
